"""The credit channel: a spread regressor lets a share react to a shift of the spread.

The registry change adds ``ru.spread_bbb`` to the regressors of ``share_price``; this test
holds the mechanism itself against simulated data: a shift of the spread in the macro paths
moves a share whose satellite reads the spread, and leaves an identical satellite without
the regressor — fitted on the same data — bit-for-bit unchanged.
"""

from dataclasses import replace
from datetime import date
from types import SimpleNamespace

import numpy as np

from mst.data.store import Observation, SeriesStore
from mst.drivers.history import history
from mst.drivers.registry import Registry
from mst.model_sdk import Check
from mst.model_sdk.contracts import MacroSimulation, UpperPaths
from mst.plugins.hier.estimate import fit
from mst.plugins.hier.simulate import simulate as simulate_hier
from mst.plugins.hier.spec import Sampler, Spec
from tests.drivers import simulated

AS_OF = date(2030, 1, 1)
#: The bank's satellite in differences over two inputs: the market and the spread. The
#: columns are (const, own lag, market@0, spread@0, market@1, spread@1); the long-run
#: loading on the spread is (-2.0 + 1.0) / (1 - 0.2) = -1.25.
GAMMA = np.array([0.1, 0.2, 1.0, -2.0, -0.5, 1.0])
SIGMA = 0.3


def _panel():
    """The simulated panel with a second input that varies, so it can be read."""
    panel = simulated.panel(240)
    rng = np.random.default_rng(9)
    y = panel.y.copy()
    y[:, 1] = np.cumsum(rng.standard_normal(len(y)))
    return replace(panel, y=y)


def _registry(regressors: list[str]) -> Registry:
    """A registry of one ``price`` driver that reads the named inputs of the panel."""
    return Registry.model_validate(
        {
            "quantities": [
                {
                    "id": "price",
                    "label": "Price",
                    "unit": "rub",
                    "transform": "identity",
                    "regressors": regressors,
                    "lags": 1,
                }
            ],
            "objects": [{"id": "sector", "class": "sector", "label": "Sector"}],
            "drivers": [
                {"quantity": "price", "object": "sector", "series": "drv.price.sector"}
            ],
        }
    )


def _store(root, panel) -> SeriesStore:
    """The share's levels, generated by the known model in differences over both inputs."""
    rng = np.random.default_rng(4)
    result = SeriesStore(root)
    x = panel.y[:, [panel.ids.index("gl.brent"), panel.ids.index("ru.key_rate")]]
    d = np.empty(len(x))
    d[0] = 50.0
    change = GAMMA[0] / (1 - GAMMA[1])
    for t in range(1, len(x)):
        dx = x[t] - x[t - 1]
        previous = x[t - 1] - x[t - 2] if t >= 2 else np.zeros(2)
        z = np.concatenate([[1.0, change], dx, previous])
        change = float(GAMMA @ z) + SIGMA * rng.standard_normal()
        d[t] = d[t - 1] + change
    result.write(
        "drv.price.sector",
        [Observation(m, float(v), m, False) for m, v in zip(panel.months, d, strict=True)],
    )
    return result


def _spec() -> Spec:
    return Spec(
        spread=0.1,
        constant_spread=10.0,
        rho_max=0.99,
        holdout=24,
        reach=12,
        differences=["price"],
        sampler=Sampler(draws=60, burn=30, seed=7),
    )


def _model(fit_):
    """The model object ``simulate`` reads: the fit and a check that serves the sector."""
    node = fit_.history.driver.index("price:sector")
    return SimpleNamespace(
        fits={"price": fit_}, checks={"price": {node: Check(None, None, 0, True, "")}}
    )


def _macro(panel, spread_shift: float, draws=3):
    """The macro simulation with the market flat and the spread shifted from month 1 on."""
    p, horizon = 3, 4
    history = np.repeat(panel.y[None, -p:], draws, axis=0)
    future = np.zeros((draws, horizon, 2))
    future[:, :, 1] = spread_shift
    paths = np.concatenate([history[:, -1:], future], axis=1)
    months = [panel.months[-1]] + [date(2030, m, 1) for m in range(1, horizon + 1)]
    return MacroSimulation(ids=panel.ids, months=months, paths=paths, history=history)


def _paths(fit_, macro):
    return simulate_hier(
        _model(fit_),
        UpperPaths(macro=macro, levels={}),
        ["price:sector"],
        [],
        shocks=np.random.default_rng(5).standard_normal((3, 64, 1)),
        seed=11,
        stream=0,
    ).paths


def test_a_shift_of_the_spread_moves_a_share_that_reads_it(tmp_path):
    panel = _panel()
    store = _store(tmp_path, panel)
    hist = history(_registry(["gl.brent", "ru.key_rate"]), "price", panel, store, AS_OF)
    fit_on = fit(hist, _spec())
    assert fit_on.differenced

    # The fitted long-run loading on the spread is the negative one the data carry.
    node = fit_on.history.nodes.index("sector")
    loading = (fit_on.gamma[:, node, 3] + fit_on.gamma[:, node, 5]) / (1 - fit_on.gamma[:, node, 1])
    assert float(np.median(loading)) < 0

    plain = _paths(fit_on, _macro(panel, 0.0))
    shifted = _paths(fit_on, _macro(panel, 10.0))
    assert not np.array_equal(plain, shifted)
    assert np.median(shifted[:, -1, 0]) < np.median(plain[:, -1, 0])


def test_a_share_whose_satellite_reads_no_spread_stays_unchanged(tmp_path):
    panel = _panel()
    store = _store(tmp_path, panel)
    hist = history(_registry(["gl.brent"]), "price", panel, store, AS_OF)
    fit_off = fit(hist, _spec())
    assert fit_off.history.x.shape[1] == 1

    plain = _paths(fit_off, _macro(panel, 0.0))
    shifted = _paths(fit_off, _macro(panel, 10.0))
    assert np.array_equal(plain, shifted)
